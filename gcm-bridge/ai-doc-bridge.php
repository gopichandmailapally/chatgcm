<?php
/**
 * Chat GCM <-> GCM Enterprises AI Document Bridge
 * Secure Internal API for automated Quotation / Estimation Generation
 */

header('Content-Type: application/json; charset=utf-8');

// Internal Secret Token for Chat GCM bridge
$BRIDGE_SECRET = 'GCM_AI_DOC_BRIDGE_SECRET_2026';

$authHeader = $_SERVER['HTTP_AUTHORIZATION'] ?? $_SERVER['HTTP_X_BRIDGE_TOKEN'] ?? '';
if (preg_match('/Bearer\s+(.*)$/i', $authHeader, $matches)) {
    $token = trim($matches[1]);
} else {
    $token = trim($authHeader);
}

// Allow local loopback calls or valid secret token
$remoteAddr = $_SERVER['REMOTE_ADDR'] ?? '';
$isLocal = in_array($remoteAddr, ['127.0.0.1', '::1']);
if (!$isLocal && $token !== $BRIDGE_SECRET) {
    http_response_code(401);
    echo json_encode(['error' => 'Unauthorized: Invalid bridge token', 'success' => false]);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['error' => 'Method Not Allowed. POST required.', 'success' => false]);
    exit;
}

$raw = file_get_contents('php://input');
$data = json_decode($raw, true);

if (!is_array($data)) {
    http_response_code(400);
    echo json_encode(['error' => 'Invalid JSON body', 'success' => false]);
    exit;
}

require_once __DIR__ . '/../includes/functions.php';

// Prepare data for buildDocument()
$companyId = $data['company_id'] ?? 'COMP-0001';
$company = getCompany($companyId);
if (!$company) {
    $company = getDefaultCompany();
    $companyId = $company['id'] ?? 'COMP-0001';
}

$cust = $data['customer'] ?? [];
$name = trim($cust['name'] ?? 'Prospective Client');
$phone = trim($cust['phone'] ?? '');
$address = trim($cust['address'] ?? ($cust['city'] ?? 'Hyderabad, Telangana'));
$state = trim($cust['state'] ?? 'Telangana');
$gstin = strtoupper(trim($cust['gstin'] ?? ''));

// Map line items
$itemDescs = [];
$itemHsns = [];
$itemQtys = [];
$itemUnits = [];
$itemRates = [];
$itemSpecs = [];
$itemGstRates = [];

$inputItems = $data['items'] ?? [];
if (empty($inputItems)) {
    http_response_code(400);
    echo json_encode(['error' => 'No line items provided', 'success' => false]);
    exit;
}

foreach ($inputItems as $it) {
    $desc = trim($it['description'] ?? $it['name'] ?? '');
    if ($desc === '') continue;
    $itemDescs[] = $desc;
    $itemHsns[] = trim($it['hsn'] ?? '5608');
    $itemQtys[] = (float)($it['qty'] ?? 1);
    $itemUnits[] = strtoupper(trim($it['unit'] ?? 'SQFT'));
    $itemRates[] = (float)($it['rate'] ?? 0);
    $itemGstRates[] = isset($it['gst_rate']) ? (float)$it['gst_rate'] : 0;
    
    // Specs array or string
    $rawSpecs = $it['specs'] ?? [];
    if (is_array($rawSpecs)) {
        $itemSpecs[] = $rawSpecs;
    } elseif (is_string($rawSpecs)) {
        $lines = explode("\n", $rawSpecs);
        $itemSpecs[] = array_values(array_filter(array_map('trim', $lines)));
    } else {
        $itemSpecs[] = [];
    }
}

// Terms
$terms = $data['terms'] ?? [
    'GST 18% as applicable or extra',
    'Transport & installation included in quoted price',
    '50% advance along with confirmed work order',
    'Balance 50% upon successful completion of work',
    'Warranty: 5-8 Years against manufacturing defect & UV degradation'
];

$post = [
    'type' => 'estimation',
    'date' => date('Y-m-d'),
    'company_id' => $companyId,
    'customer_type' => $data['customer_type'] ?? 'client',
    'sale_unit_mode' => $data['sale_unit_mode'] ?? 'sqft',
    'bt_name' => $name,
    'bt_phone' => $phone,
    'bt_whatsapp' => $phone,
    'bt_address' => $address,
    'bt_state' => $state,
    'bt_gstin' => $gstin,
    
    'item_desc' => $itemDescs,
    'item_hsn' => $itemHsns,
    'item_qty' => $itemQtys,
    'item_unit' => $itemUnits,
    'item_rate' => $itemRates,
    'item_specs' => $itemSpecs,
    'item_gst_rate' => $itemGstRates,
    
    'discount_type' => $data['discount_type'] ?? 'percent',
    'discount_percent' => (float)($data['discount_percent'] ?? 0),
    'discount_flat' => (float)($data['discount_flat'] ?? 0),
    
    'is_gst' => isset($data['is_gst']) ? (bool)$data['is_gst'] : false,
    'gst_mode' => $data['gst_mode'] ?? 'cgst_sgst',
    
    'terms' => $terms,
    'notes' => trim($data['notes'] ?? 'Auto-generated by Chat GCM AI Brain based on verified measurements and specs.'),
    'show_signature' => true,
    'show_stamp' => true,
    'show_bank' => true,
    'show_russea' => false,
    'status' => 'draft',
    'estimation_subtype' => $data['estimation_subtype'] ?? 'normal',
    'turnkey_config' => $data['turnkey_config'] ?? null,
];

// Build document using existing core function
$doc = buildDocument($post);

// Ensure doc is tagged with AI source
$doc['source'] = 'chat_gcm_ai';
$doc['source_channel'] = $data['channel'] ?? 'web_chat';
$doc['ai_conversation_id'] = $data['conversation_id'] ?? null;

// Save document to documents.json and increment counters.json
saveDocument($doc);

// Sync customer to customers.json if phone or name given
$customerId = null;
if ($name || $phone) {
    $customers = getAllCustomers();
    $found = false;
    foreach ($customers as $c) {
        if (($phone && ($c['phone'] ?? '') === $phone) || ($name && strtolower($c['name'] ?? '') === strtolower($name))) {
            $customerId = $c['id'];
            $found = true;
            break;
        }
    }
    if (!$found) {
        $customerId = generateCustomerId();
        $newCust = [
            'id' => $customerId,
            'name' => $name,
            'phone' => $phone,
            'email' => $cust['email'] ?? '',
            'address' => $address,
            'state' => $state,
            'gstin' => $gstin,
            'company' => $name,
            'created_at' => date('c'),
        ];
        saveCustomer($newCust);
    }
    // Link customer_id in document
    $doc['customer_id'] = $customerId;
    saveDocument($doc);
}

// Generate full response
$domain = 'https://gcm.enterprises';
$viewUrl = $domain . '/admin/view.php?id=' . urlencode($doc['id']);
$pdfUrl  = $domain . '/admin/view.php?id=' . urlencode($doc['id']) . '&mode=print';
$convertInvoiceUrl = $domain . '/admin/ajax.php?action=convert&id=' . urlencode($doc['id']) . '&to=tax_invoice';
$convertBillUrl    = $domain . '/admin/ajax.php?action=convert&id=' . urlencode($doc['id']) . '&to=bill';

echo json_encode([
    'success' => true,
    'doc_id' => $doc['id'],
    'doc_type' => $doc['type'],
    'customer_id' => $customerId,
    'company_id' => $company['id'],
    'company_name' => $company['name'],
    'subtotal' => $doc['subtotal'],
    'discount_amount' => $doc['discount_amount'],
    'taxable_value' => $doc['taxable_value'],
    'grand_total' => $doc['grand_total'],
    'amount_in_words' => $doc['amount_in_words'],
    'view_url' => $viewUrl,
    'pdf_url' => $pdfUrl,
    'convert_invoice_url' => $convertInvoiceUrl,
    'convert_bill_url' => $convertBillUrl,
    'created_at' => $doc['created_at'],
]);
